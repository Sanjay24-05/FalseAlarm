"""Write frontend/src/generated/api.ts from the backend's response models.

Run after changing a model in false_alarm.api.schemas or false_alarm.domain.models:

    python backend/scripts/generate_types.py

tests/test_generated_types.py fails while the committed file is stale.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "frontend" / "src" / "generated" / "api.ts"
sys.path.insert(0, str(ROOT / "backend" / "src"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from false_alarm.api.schemas import PUBLIC_MODELS  # noqa: E402

HEADER = (
    "// Generated by backend/scripts/generate_types.py from the backend's response models. Do not edit.\n"
    "// Every field is always present in API responses, so none is optional.\n"
)


def _type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        parts: list[str] = []
        for option in schema["anyOf"]:
            rendered = _type(option)
            if rendered not in parts:
                parts.append(rendered)
        # Keep null last so `T | null` reads naturally.
        return " | ".join(sorted(parts, key=lambda part: part == "null"))
    kind = schema.get("type")
    if kind == "array":
        item = _type(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object":
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(
        kind, "unknown"
    )


def _interface(name: str, schema: dict) -> str:
    lines = []
    if schema.get("description"):
        lines.append(f"/** {' '.join(schema['description'].split())} */")
    lines.append(f"export interface {name} {{")
    for field, field_schema in schema.get("properties", {}).items():
        lines.append(f"  {field}: {_type(field_schema)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    _, schema = models_json_schema(
        [(model, "serialization") for model in PUBLIC_MODELS], ref_template="#/$defs/{model}"
    )
    definitions = schema["$defs"]
    blocks = [_interface(name, definitions[name]) for name in sorted(definitions)]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
